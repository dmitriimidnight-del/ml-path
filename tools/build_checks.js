const stem = w => w.toLowerCase().replace(/ё/g, "е").slice(0, 5);
const toks = s => (String(s).match(/[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё_0-9]{3,}/g) || []).map(stem);
const STOP = new Set(["котор", "этого", "чтобы", "можно", "потом", "почем", "какой", "какие", "сколь", "всего", "самый",
  "когда", "print", "impor", "будет", "нужно", "здесь", "всегд", "разны", "очень", "этот", "такой", "тольк", "более",
  "после", "перед", "между", "через", "модел", "текст"]);

const out = {};
let total = 0, covered = 0;
const uncovered = [];
PATH.projects.forEach(p => (p.theory || []).forEach(t => {
  const key = p.id + "." + t.id;
  const secT = t.sections.map(s => toks([s.h, (s.p || []).join(" "), s.code || "", s.note || "", s.out || ""].join(" "))
    .filter(x => !STOP.has(x)));
  const df = {};
  secT.forEach(ts => new Set(ts).forEach(x => { df[x] = (df[x] || 0) + 1; }));
  const map = t.sections.map(() => []);
  t.quiz.forEach((qq, qi) => {
    let best = OVERRIDES[key + ".q" + qi];
    if (best === undefined) {
      const qt = new Set(toks([qq.q, qq.options[qq.answer], qq.why].join(" ")).filter(x => !STOP.has(x)));
      let bs = 0; best = 0;
      secT.forEach((ts, si) => {
        const set = new Set(ts); let sc = 0;
        qt.forEach(x => { if (set.has(x)) sc += Math.log(1 + secT.length / df[x]); });
        if (sc >= bs) { bs = sc; best = si; }
      });
    }
    map[best].push(qi);
  });
  const add = (NEW[key] || []).map((n, k) => {
    if (!t.sections[n.sec]) throw new Error("нет раздела " + key + " #" + n.sec);
    if (n.options.length !== 4 || new Set(n.options).size !== 4) throw new Error("варианты " + key + " " + n.q);
    map[n.sec].push(t.quiz.length + k);
    return { q: n.q, options: n.options, answer: n.answer, why: n.why };
  });
  t.sections.forEach((s, si) => {
    total++;
    if (map[si].length || s.out) covered++; else uncovered.push(key + " #" + si + " " + s.h);
  });
  out[key] = { add, map };
}));

